/* Hardcore Worlds: Death Toll — death map. Plots each death's hiscore location on the OSRS Wiki's map of Gielinor. */
(function () {
  "use strict";
  const $ = (s, el = document) => el.querySelector(s);
  const fmt = n => (n == null ? "—" : Number(n).toLocaleString("en-US"));
  const esc = s => String(s ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

  async function load(url) {
    try {
      const r = await fetch(url);
      if (!r.ok) return null;
      return await r.json();
    } catch (e) { return null; }
  }

  function ago(ms) {
    const s = Math.max(0, (Date.now() - ms) / 1000);
    if (s < 90) return "just now";
    if (s < 5400) return Math.round(s / 60) + "m ago";
    if (s < 129600) return Math.round(s / 3600) + "h ago";
    return Math.round(s / 86400) + "d ago";
  }

  /* ---------------- shared header: assets/nav.js ---------------- */
  function chrome(gy) {
    deathTollHeader(gy && gy.counts ? gy.counts.all_time : 0);
  }

  /* ---------------- map tiles ----------------
     OSRS Wiki tiles (generated by github.com/osrs-wiki/osrs-wiki-maps): at zoom z one game tile is 2^z px,
     so with L.CRS.Simple a game tile (x, y) is simply latlng [y, x]. The server counts tile rows northward
     and Leaflet southward, hence row = -y - 1. Map 0 is the Gielinor surface, plane 0 the ground floor.
     The wiki retires old tile versions, so the pin below is only a starting point: if it stops serving,
     the current version is read off a rendered wiki article and remembered. */
  const TILES = "https://maps.runescape.wiki/osrs/versions/";
  const PINNED = "2026-10-20_a";
  const VERSION_RE = /versions\/(\d{4}-\d\d-\d\d_[a-z])\//;
  const store = {
    get() { try { return JSON.parse(localStorage.getItem("dt-map-version")); } catch (e) { return null; } },
    set(v) { try { localStorage.setItem("dt-map-version", JSON.stringify({ v, at: Date.now() })); } catch (e) { /* private mode */ } },
  };
  async function currentVersion() {
    for (const page of ["Lumbridge", "Varrock", "Wilderness"]) {
      const j = await load(`https://oldschool.runescape.wiki/api.php?action=parse&format=json&origin=*&prop=text&page=${page}`);
      const m = j && JSON.stringify(j).replace(/\\\//g, "/").match(VERSION_RE);
      if (m) return m[1];
    }
    return null;
  }
  const WikiTiles = L.TileLayer.extend({
    getTileUrl(c) { return `${TILES}${this.options.version}/tiles/rendered/0/${c.z}/0_${c.x}_${-c.y - 1}.png`; },
  });
  const SURFACE = L.latLngBounds([2496, 1024], [4224, 4096]);   // generous box around the surface map; keeps requests off empty sea

  const toLatLng = (x, y) => L.latLng(y + 0.5, x + 0.5);   // centre of the game tile
  // Most dungeons sit exactly 6400 tiles north of the ground above them (Taverley Dungeon under Taverley,
  // the Barrows crypts under the mounds), so an underground death is drawn at the spot above it.
  // Anything that still falls outside the drawn map (instances, unmapped areas) is counted, never drawn in the void.
  const UNDERGROUND = 6400;
  function place({ x, y }) {
    const under = y >= UNDERGROUND;
    const py = under ? y - UNDERGROUND : y;
    return SURFACE.contains(toLatLng(x, py)) ? { x, y: py, under } : null;
  }
  const regionOf = (x, y) => ((x >> 6) << 8) | (y >> 6);

  /* ---------------- data ---------------- */
  async function deathsData() {
    const real = await load(`data/graveyard.json?t=${Math.floor(Date.now() / 60000)}`);
    if (real && real.status === "live") return { real, deaths: real.deaths || [], sample: false };
    const sample = await load("assets/sample-map.json");
    const now = Date.now();
    return { real, sample: true, deaths: ((sample && sample.deaths) || []).map(d => ({ ...d, time: now - d.age_min * 60000 })) };
  }

  const FATE = { died: ["DIED", "#ff3b45"], reset: ["RESET", "#ff981f"], fallen: ["FALLEN", "#a399ad"] };

  async function main() {
    const [{ real, deaths, sample }, regionFile] = await Promise.all([deathsData(), load("assets/map-regions.json")]);
    chrome(real && real.status === "live" ? real : null);
    const names = (regionFile && regionFile.regions) || {};
    if (sample) {
      $("#badge").hidden = false;
    }

    const located = deaths.filter(d => d.location && Number.isFinite(d.location.x) && Number.isFinite(d.location.y));
    const plotted = located.map(d => ({ ...d, at: place(d.location) })).filter(d => d.at);
    const unplaced = located.length - plotted.length;
    const underground = plotted.filter(d => d.at.under).length;

    const map = L.map("map", {
      crs: L.CRS.Simple, minZoom: -3, maxZoom: 5, zoomSnap: 1, attributionControl: false,
      maxBounds: SURFACE.pad(0.15),
      maxBoundsViscosity: 0.8,
    });
    L.control.attribution({ prefix: '<a href="https://leafletjs.com">Leaflet</a>' }).addTo(map);

    const saved = store.get();
    let version = saved && saved.v > PINNED ? saved.v : PINNED, loaded = 0, failed = 0, retried = false;
    const tiles = new WikiTiles("", {
      version, bounds: SURFACE, minZoom: -3, maxZoom: 5, minNativeZoom: -3, maxNativeZoom: 3, tileSize: 256,
      attribution: 'Tiles: <a href="https://oldschool.runescape.wiki/w/RuneScape:Map">OSRS Wiki</a>, CC BY-NC-SA 3.0',
      errorTileUrl: "data:image/gif;base64,R0lGODlhAQABAAAAACH5BAEKAAEALAAAAAABAAEAAAICTAEAOw==",
    }).addTo(map);
    tiles.on("tileload", () => { loaded++; $("#map-msg").hidden = true; });
    tiles.on("tileerror", async () => {
      // A few gaps are normal (the server skips all-black tiles); nothing loading at all means the version was retired.
      if (++failed < 6 || loaded || retried) return;
      retried = true;
      const v = await currentVersion();
      if (v && v !== version) { version = v; store.set(v); tiles.options.version = v; tiles.redraw(); return; }
      $("#map-msg").textContent = "The map tiles could not be loaded right now. The points are still placed correctly.";
      $("#map-msg").hidden = false;
    });

    if (plotted.length) {
      const heatPts = plotted.map(d => { const p = toLatLng(d.at.x, d.at.y); return [p.lat, p.lng, 1]; });
      L.heatLayer(heatPts, {
        radius: 22, blur: 18, minOpacity: 0.3, maxZoom: -3, max: Math.max(2, Math.round(Math.sqrt(plotted.length) / 2)),
        gradient: { 0.25: "#5b3fa0", 0.55: "#b3121b", 0.8: "#ff981f", 1: "#ffff00" },
      }).addTo(map);
      const renderer = L.canvas({ padding: 0.5, tolerance: 10 });   // generous hit area for fingers
      for (const d of plotted) {
        const { x, y, plane } = d.location;
        const [label, color] = FATE[d.fate] || FATE.died;
        const rid = regionOf(x, y);
        L.circleMarker(toLatLng(d.at.x, d.at.y), { renderer, radius: 5, weight: 1.5, color: "#000", fillColor: color, fillOpacity: 0.95 })
          .bindPopup(`<div class="dp">${sample ? '<span class="tag gold">SAMPLE</span>' : ""}
            <b>${esc(d.name)}</b>
            <span class="l">${fmt(d.total)} <small>total</small> · <em style="color:${color}">${label}</em></span>
            <span>${d.time ? ago(d.time) : ""}${d.world ? ` · W${d.world}` : ""}</span>
            <span>${esc(names[rid] || "")}${names[rid] ? " · " : ""}${x}, ${y}${plane ? ` · floor ${plane}` : ""}</span>
            ${d.at.under ? "<span>Underground · shown at the spot above</span>" : ""}</div>`,
            { maxWidth: 240, autoPanPadding: [12, 12] })
          .addTo(map);
      }
      // Open on where most deaths are: trim the outer tenth on each side so one far-off grave can't zoom a phone out to a speck.
      const pct = (vals, q) => vals.sort((a, b) => a - b)[Math.floor(q * (vals.length - 1))];
      const xs = plotted.map(d => d.at.x), ys = plotted.map(d => d.at.y);
      const core = L.latLngBounds(toLatLng(pct(xs, 0.1), pct(ys, 0.1)), toLatLng(pct(xs, 0.9), pct(ys, 0.9))).pad(0.15);
      map.fitBounds(core, { maxZoom: 1 });
      if (map.getZoom() < -2) map.setView(core.getCenter(), -2);
    } else {
      map.setView([3300, 3100], -1);
      $("#map-msg").textContent = located.length ? "Every recorded death so far was in an instance or an area off the map, so there is nothing to plot yet." : "No death locations recorded yet.";
      $("#map-msg").hidden = false;
    }

    /* ---------------- counts + deadliest regions ---------------- */
    // Regions use the real tile (so a dungeon keeps its own name); "fly" goes to where its graves are drawn.
    const groups = new Map(), drawnAt = new Map();
    for (const d of plotted) {
      const rid = regionOf(d.location.x, d.location.y);
      groups.set(rid, (groups.get(rid) || 0) + 1);
      if (!drawnAt.has(rid)) drawnAt.set(rid, [d.at.x - d.at.x % 64, d.at.y - d.at.y % 64]);
    }
    const S = sample ? `<em class="tag sample">SAMPLE</em>` : "";   // made-up numbers are always labelled
    const top = [...groups].sort((a, b) => b[1] - a[1] || a[0] - b[0]).slice(0, 10);
    $("#counts").innerHTML = `
      <div><b>${fmt(plotted.length)}</b><span>${S}ON THE MAP${underground ? ` · ${fmt(underground)} UNDERGROUND` : ""}</span></div>
      <div><b>${fmt(unplaced)}</b><span>${S}IN INSTANCES (BOSSES, RAIDS, MINIGAMES) OR OFF THE MAP</span></div>
      <div><b>${fmt(deaths.length - located.length)}</b><span>${S}NO LOCATION RECORDED</span></div>
      <div><b>${fmt(groups.size)}</b><span>${S}REGIONS WITH A DEATH</span></div>`;
    $("#regions").innerHTML = top.map(([rid, n], i) => {
      const rx = rid >> 8, ry = rid & 255;
      const coords = `x ${rx * 64}–${rx * 64 + 63}, y ${ry * 64}–${ry * 64 + 63}`;
      return `<tr data-r="${rid}" tabindex="0" role="button" aria-label="Show ${esc(names[rid] || coords)} on the map">
        <td>${i + 1}</td><td class="n">${names[rid] ? `${esc(names[rid])}<small>${coords}</small>` : `Region ${rx}, ${ry}<small>${coords}</small>`}${S}</td><td class="y">${fmt(n)}</td></tr>`;
    }).join("") || `<tr><td colspan="3" class="note">Nothing plotted yet.</td></tr>`;
    function fly(row) {
      if (!row) return;
      const [bx, by] = drawnAt.get(+row.dataset.r);
      $(".map-shell").scrollIntoView({ behavior: "smooth", block: "start" });
      map.flyToBounds([[by, bx], [by + 64, bx + 64]], { maxZoom: 2 });
    }
    $("#regions").addEventListener("click", e => fly(e.target.closest("[data-r]")));
    $("#regions").addEventListener("keydown", e => { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); fly(e.target.closest("[data-r]")); } });

    window.deathMap = { map, tiles, toLatLng };   // used by tools/test-map.js
  }

  main();
})();
